CREATE TABLE IF NOT EXISTS MAP_GUIDE (
    MAP_ID VARCHAR(30) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    ADDRESS VARCHAR(300),
    LATITUDE DECIMAL(10,7),
    LONGITUDE DECIMAL(10,7),
    DESCRIPTION VARCHAR(2000),
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_MAP_GUIDE PRIMARY KEY (MAP_ID)
);

CREATE INDEX IF NOT EXISTS IDX_MAP_GUIDE_USE ON MAP_GUIDE(USE_YN, TITLE);

