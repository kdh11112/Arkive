-- 2단계: 버전별 약관과 사용자 동의 이력.
-- 아래 본문은 이식용 자리표시자다. 실제 서비스·개인정보·마케팅 문구는 법무/개인정보 담당자 검토 후
-- 새 VERSION 행을 추가하고 기존 행의 USE_YN을 'N'으로 바꾼다. 기존 동의 이력은 삭제하지 않는다.
CREATE TABLE IF NOT EXISTS TERMS (
    TERMS_ID VARCHAR(30) NOT NULL,
    TERMS_TYPE VARCHAR(30) NOT NULL,
    VERSION VARCHAR(20) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    CONTENT CLOB NOT NULL,
    REQUIRED_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    EFFECTIVE_DT DATE,
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_TERMS PRIMARY KEY (TERMS_ID),
    CONSTRAINT UK_TERMS_TYPE_VERSION UNIQUE (TERMS_TYPE, VERSION)
);

CREATE TABLE IF NOT EXISTS USER_TERMS_CONSENT (
    USER_ID VARCHAR(50) NOT NULL,
    TERMS_ID VARCHAR(30) NOT NULL,
    CONSENT_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    CONSENT_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USER_TERMS_CONSENT PRIMARY KEY (USER_ID, TERMS_ID),
    CONSTRAINT FK_USER_TERMS_CONSENT_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_TERMS_CONSENT_TERMS FOREIGN KEY (TERMS_ID) REFERENCES TERMS(TERMS_ID)
);

