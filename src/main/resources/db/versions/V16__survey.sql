-- 설문관리 세트. 템플릿 → 설문 → 질문 → 항목 → 참여 → 통계 순으로 사용한다.
-- 템플릿은 설문 작성 시 제목·설명·익명 여부를 채우는 샘플 용도이며,
-- 질문 유형은 SINGLE(단일선택)/MULTI(복수선택)/TEXT(주관식) 샘플 상수다.
-- 대상 프로젝트의 공통코드·설문 정책으로 교체한다.
CREATE TABLE IF NOT EXISTS SURVEY_TEMPLATE (
    TEMPLATE_ID VARCHAR(30) NOT NULL,
    TEMPLATE_NM VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(1000),
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_SURVEY_TEMPLATE PRIMARY KEY (TEMPLATE_ID)
);

CREATE TABLE IF NOT EXISTS SURVEY (
    SURVEY_ID VARCHAR(30) NOT NULL,
    TEMPLATE_ID VARCHAR(30),
    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(2000),
    START_DE VARCHAR(10) NOT NULL,
    END_DE VARCHAR(10) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'DRAFT' NOT NULL,
    ANONYMOUS_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_SURVEY PRIMARY KEY (SURVEY_ID)
);

CREATE TABLE IF NOT EXISTS SURVEY_QUESTION (
    QUESTION_ID VARCHAR(30) NOT NULL,
    SURVEY_ID VARCHAR(30) NOT NULL,
    QUESTION_NO INTEGER DEFAULT 1 NOT NULL,
    QUESTION_TXT VARCHAR(1000) NOT NULL,
    QUESTION_TYPE VARCHAR(20) DEFAULT 'SINGLE' NOT NULL,
    REQUIRED_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    ORDR INTEGER DEFAULT 0 NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_SURVEY_QUESTION PRIMARY KEY (QUESTION_ID),
    CONSTRAINT FK_SURVEY_QUESTION_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY(SURVEY_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SURVEY_ITEM (
    ITEM_ID VARCHAR(30) NOT NULL,
    QUESTION_ID VARCHAR(30) NOT NULL,
    ITEM_TXT VARCHAR(500) NOT NULL,
    ORDR INTEGER DEFAULT 0 NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SURVEY_ITEM PRIMARY KEY (ITEM_ID),
    CONSTRAINT FK_SURVEY_ITEM_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES SURVEY_QUESTION(QUESTION_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SURVEY_PARTICIPATION (
    PARTICIPATION_ID VARCHAR(30) NOT NULL,
    SURVEY_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    SUBMIT_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SURVEY_PARTICIPATION PRIMARY KEY (PARTICIPATION_ID),
    CONSTRAINT UK_SURVEY_PARTICIPATION UNIQUE (SURVEY_ID, USER_ID),
    CONSTRAINT FK_SURVEY_PARTICIPATION_SURVEY FOREIGN KEY (SURVEY_ID) REFERENCES SURVEY(SURVEY_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SURVEY_ANSWER (
    ANSWER_ID VARCHAR(30) NOT NULL,
    PARTICIPATION_ID VARCHAR(30) NOT NULL,
    QUESTION_ID VARCHAR(30) NOT NULL,
    ITEM_ID VARCHAR(30),
    ANSWER_TXT VARCHAR(2000),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SURVEY_ANSWER PRIMARY KEY (ANSWER_ID),
    CONSTRAINT FK_SURVEY_ANSWER_PARTICIPATION FOREIGN KEY (PARTICIPATION_ID) REFERENCES SURVEY_PARTICIPATION(PARTICIPATION_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_SURVEY_STATUS ON SURVEY(STATUS, START_DE, END_DE);
CREATE INDEX IF NOT EXISTS IDX_SURVEY_QUESTION_SURVEY ON SURVEY_QUESTION(SURVEY_ID, ORDR);
CREATE INDEX IF NOT EXISTS IDX_SURVEY_ITEM_QUESTION ON SURVEY_ITEM(QUESTION_ID, ORDR);
CREATE INDEX IF NOT EXISTS IDX_SURVEY_ANSWER_PARTICIPATION ON SURVEY_ANSWER(PARTICIPATION_ID);
CREATE INDEX IF NOT EXISTS IDX_SURVEY_ANSWER_QUESTION ON SURVEY_ANSWER(QUESTION_ID, ITEM_ID);

