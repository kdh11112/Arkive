-- 약식결재. 기안(DRAFT) → 상신(SUBMITTED) → 승인(APPROVED)/반려(REJECTED),
-- 상신 취소(CANCELLED) 흐름을 문서 1건 + 이력으로 기록한다.
-- 문서구분은 샘플 상수(GENERAL/LEAVE/EXPENSE/ETC)를 쓰며, 대상 프로젝트에서
-- 공통코드 COM75로 교체할 때 이 테이블의 DOC_TYPE 값과 매핑한다.
CREATE TABLE IF NOT EXISTS APPROVAL_DOC (
    DOC_ID VARCHAR(30) NOT NULL,
    DOC_TYPE VARCHAR(20) DEFAULT 'GENERAL' NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    CONTENT VARCHAR(4000),
    DRAFTER_ID VARCHAR(50) NOT NULL,
    APPROVER_ID VARCHAR(50) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'DRAFT' NOT NULL,
    SUBMIT_DT TIMESTAMP,
    APPROVED_DT TIMESTAMP,
    REJECT_REASON VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_APPROVAL_DOC PRIMARY KEY (DOC_ID)
);

CREATE TABLE IF NOT EXISTS APPROVAL_HISTORY (
    HISTORY_ID VARCHAR(30) NOT NULL,
    DOC_ID VARCHAR(30) NOT NULL,
    ACTION VARCHAR(20) NOT NULL,
    ACTOR_ID VARCHAR(50) NOT NULL,
    NOTE VARCHAR(500),
    ACTION_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APPROVAL_HISTORY PRIMARY KEY (HISTORY_ID)
);

CREATE INDEX IF NOT EXISTS IDX_APPROVAL_DOC_DRAFTER ON APPROVAL_DOC(DRAFTER_ID, STATUS);
CREATE INDEX IF NOT EXISTS IDX_APPROVAL_DOC_APPROVER ON APPROVAL_DOC(APPROVER_ID, STATUS);
CREATE INDEX IF NOT EXISTS IDX_APPROVAL_HISTORY_DOC ON APPROVAL_HISTORY(DOC_ID);

