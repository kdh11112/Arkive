-- HR 세트. 기념일·경조사·포상은 사용자(APP_USER)에 연결된 기록이며,
-- 개인연차 화면은 기존 LEAVE_BALANCE/LEAVE_REQUEST와 DUTY를 사용자 단위로 모아 보여준다.
-- 유형 코드는 샘플 상수이므로 대상 프로젝트의 공통코드로 교체한다.
CREATE TABLE IF NOT EXISTS HR_ANNIVERSARY (
    ANNIV_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    ANNIV_TYPE VARCHAR(20) DEFAULT 'BIRTH' NOT NULL,
    ANNIV_DE VARCHAR(5) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    REMARK VARCHAR(500),
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_HR_ANNIVERSARY PRIMARY KEY (ANNIV_ID)
);

CREATE TABLE IF NOT EXISTS HR_EVENT (
    EVENT_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    EVENT_TYPE VARCHAR(20) DEFAULT 'WEDDING' NOT NULL,
    EVENT_DE VARCHAR(10) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    AMOUNT DECIMAL(12,0) DEFAULT 0 NOT NULL,
    REMARK VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_HR_EVENT PRIMARY KEY (EVENT_ID)
);

CREATE TABLE IF NOT EXISTS HR_REWARD (
    REWARD_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    REWARD_TYPE VARCHAR(20) DEFAULT 'EXCELLENT' NOT NULL,
    REWARD_DE VARCHAR(10) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    AMOUNT DECIMAL(12,0) DEFAULT 0 NOT NULL,
    REWARDER VARCHAR(100),
    REMARK VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_HR_REWARD PRIMARY KEY (REWARD_ID)
);

CREATE INDEX IF NOT EXISTS IDX_HR_ANNIVERSARY_USER ON HR_ANNIVERSARY(USER_ID);
CREATE INDEX IF NOT EXISTS IDX_HR_ANNIVERSARY_DE ON HR_ANNIVERSARY(ANNIV_DE);
CREATE INDEX IF NOT EXISTS IDX_HR_EVENT_USER ON HR_EVENT(USER_ID);
CREATE INDEX IF NOT EXISTS IDX_HR_EVENT_DE ON HR_EVENT(EVENT_DE);
CREATE INDEX IF NOT EXISTS IDX_HR_REWARD_USER ON HR_REWARD(USER_ID);
CREATE INDEX IF NOT EXISTS IDX_HR_REWARD_DE ON HR_REWARD(REWARD_DE);

