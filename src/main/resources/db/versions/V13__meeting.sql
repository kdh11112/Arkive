-- 회의실관리 + 회의실예약.
-- 회의실 마스터 없이 예약할 수 없고, 같은 회의실·날짜의 시간대가 겹치면 예약을 거부한다.
CREATE TABLE IF NOT EXISTS MEETING_ROOM (
    ROOM_ID VARCHAR(30) NOT NULL,
    ROOM_NM VARCHAR(100) NOT NULL,
    LOCATION VARCHAR(200),
    CAPACITY INT DEFAULT 0 NOT NULL,
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REMARK VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_MEETING_ROOM PRIMARY KEY (ROOM_ID)
);

CREATE TABLE IF NOT EXISTS MEETING_RESERVATION (
    RESERVE_ID VARCHAR(30) NOT NULL,
    ROOM_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    RESERVE_DE VARCHAR(10) NOT NULL,
    START_TIME VARCHAR(5) NOT NULL,
    END_TIME VARCHAR(5) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    PURPOSE VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MEETING_RESERVATION PRIMARY KEY (RESERVE_ID)
);

CREATE INDEX IF NOT EXISTS IDX_MEETING_RESV_ROOM ON MEETING_RESERVATION(ROOM_ID, RESERVE_DE);
CREATE INDEX IF NOT EXISTS IDX_MEETING_RESV_USER ON MEETING_RESERVATION(USER_ID, RESERVE_DE);

