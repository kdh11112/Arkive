-- 2단계: Q&A 내·외부 구분과 감사 로그.
-- ASK_TYPE: PUBLIC(외부 공개), INTERNAL(로그인 사용자만 열람).
ALTER TABLE BOARD ADD COLUMN ASK_TYPE VARCHAR(20) DEFAULT 'PUBLIC' NOT NULL;

UPDATE BOARD
SET ASK_TYPE = 'PUBLIC'
WHERE BOARD_TYPE = 'QNA' AND (ASK_TYPE IS NULL OR ASK_TYPE = '');

CREATE INDEX IF NOT EXISTS IDX_BOARD_QNA_ASK ON BOARD(BOARD_TYPE, ASK_TYPE, REGIST_DT);

-- 감사 로그. 원문 비밀번호·주민번호·본문은 저장하지 않는다.
-- DETAIL에는 대상 식별자와 결과 정도만 남긴다.
CREATE TABLE IF NOT EXISTS AUDIT_LOG (
    LOG_ID VARCHAR(40) NOT NULL,
    EVENT_TYPE VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50),
    USER_NM VARCHAR(100),
    MENU_ID VARCHAR(20),
    TARGET_TYPE VARCHAR(50),
    TARGET_ID VARCHAR(100),
    REQUEST_URI VARCHAR(500),
    HTTP_METHOD VARCHAR(10),
    CLIENT_IP VARCHAR(64),
    RESULT VARCHAR(20) DEFAULT 'SUCCESS' NOT NULL,
    DETAIL VARCHAR(1000),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);

CREATE INDEX IF NOT EXISTS IDX_AUDIT_LOG_DT ON AUDIT_LOG(REGIST_DT);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_LOG_EVENT ON AUDIT_LOG(EVENT_TYPE, REGIST_DT);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_LOG_USER ON AUDIT_LOG(USER_ID, REGIST_DT);

