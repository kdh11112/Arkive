-- 게시글 댓글. 1단만 지원한다(대댓글 없음). 로그인 사용자만 작성한다.
-- 작성자 ID와 표시 이름을 함께 저장해 사용자 테이블 조인 없이 목록을 그린다.
CREATE TABLE IF NOT EXISTS BOARD_COMMENT (
    COMMENT_ID VARCHAR(50) NOT NULL,
    BOARD_ID VARCHAR(50) NOT NULL,
    CONTENT VARCHAR(1000) NOT NULL,
    REGISTER VARCHAR(50) NOT NULL,
    REGISTER_NM VARCHAR(100),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_BOARD_COMMENT PRIMARY KEY (COMMENT_ID),
    CONSTRAINT FK_BOARD_COMMENT_BOARD FOREIGN KEY (BOARD_ID) REFERENCES BOARD(BOARD_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_BOARD_COMMENT_BOARD ON BOARD_COMMENT(BOARD_ID);
