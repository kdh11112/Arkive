-- 사용자. HSQLDB 예약어 회피용으로 APP_USER. 비밀번호는 bcrypt 해시만 저장.
-- ADMIN_YN으로 관리자/일반을 가른다. 초기 admin/Admin1234! 은 개발용. 운영 전 변경.
CREATE TABLE IF NOT EXISTS APP_USER (
    USER_ID VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(200) NOT NULL,
    USER_NM VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100),
    FAILED_CNT INTEGER DEFAULT 0 NOT NULL,
    LOCK_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    ADMIN_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_APP_USER PRIMARY KEY (USER_ID)
);

