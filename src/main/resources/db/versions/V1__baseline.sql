--   ME02010300은 Swagger 유지. 구 V27이 같은 ID로 사용자관리를 MERGE해서 무적용된
--   버그가 있었으므로 사용자관리는 ME02010400 신규 ID로 둔다.
--   메뉴 표시명·경로의 trailing 공백을 제거했다 (화면 표시 동일).

