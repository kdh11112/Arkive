--   menu_author, user (구 V2): 매퍼·자바에서 참조 0건. 로그인은 APP_USER를 쓴다.
--   SAMPLE/IDS 시드 6건+7: eGovFrame 샘플 CRUD용. 샘플 매퍼가 살아 있어 유지한다.
--   테스트 데이터(BOARD/COMM_CODE/ATCH_FILE 행): 이식 대상 아님. 제외.
