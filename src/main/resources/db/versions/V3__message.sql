-- 쪽지. 보낸사람·받는사람별 삭제 플래그를 따로 두어 한쪽이 지워도 상대 함에는 남긴다.
CREATE TABLE IF NOT EXISTS MESSAGE (
    MSG_ID VARCHAR(50) NOT NULL,
    SENDER_ID VARCHAR(50) NOT NULL,
    SENDER_NM VARCHAR(100),
    RECEIVER_ID VARCHAR(50) NOT NULL,
    RECEIVER_NM VARCHAR(100),
    TITLE VARCHAR(200) NOT NULL,
    CONTENT VARCHAR(4000),
    READ_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    READ_DT TIMESTAMP,
    SENT_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    SENDER_DEL_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    RECEIVER_DEL_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_MESSAGE PRIMARY KEY (MSG_ID)
);

CREATE INDEX IF NOT EXISTS IDX_MESSAGE_RECEIVER ON MESSAGE(RECEIVER_ID);
CREATE INDEX IF NOT EXISTS IDX_MESSAGE_SENDER ON MESSAGE(SENDER_ID);

