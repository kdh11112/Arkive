-- 2단계: TOTP 2단계 인증.
-- 비밀키는 FieldCryptoService(AES-GCM)로 암호화해 저장한다. 평문 비밀키는 저장하지 않는다.
-- 복구코드는 원문이 아니라 SHA-256 해시만 저장하고, 사용 시 USED_YN='Y'로 1회만 허용한다.
CREATE TABLE IF NOT EXISTS APP_USER_TOTP (
    USER_ID VARCHAR(50) NOT NULL,
    SECRET_ENC VARCHAR(1000) NOT NULL,
    ENABLED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONFIRMED_DT TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_APP_USER_TOTP PRIMARY KEY (USER_ID),
    CONSTRAINT FK_APP_USER_TOTP_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS APP_USER_TOTP_RECOVERY (
    RECOVERY_ID VARCHAR(50) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    CODE_HASH VARCHAR(64) NOT NULL,
    USED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    USED_DT TIMESTAMP,
    CONSTRAINT PK_APP_USER_TOTP_RECOVERY PRIMARY KEY (RECOVERY_ID),
    CONSTRAINT FK_APP_USER_TOTP_RECOVERY_TOTP FOREIGN KEY (USER_ID) REFERENCES APP_USER_TOTP(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_APP_USER_TOTP_RECOVERY_USER ON APP_USER_TOTP_RECOVERY(USER_ID, USED_YN);
