-- 휴가관리. 연차 부여/사용일수는 LEAVE_BALANCE에 두고, 승인 시 차감·승인 취소 시 환원한다.
-- 신청 기간은 같은 연도만 허용한다. 일수는 주말·공휴일(HOLIDAY)을 제외한 평일 기준이며,
-- 반차는 시작일=종료일일 때 0.5일로 계산한다. 대상 프로젝트의 휴가 정책에 맞게 교체한다.
CREATE TABLE IF NOT EXISTS LEAVE_BALANCE (
    USER_ID VARCHAR(50) NOT NULL,
    LEAVE_YEAR VARCHAR(4) NOT NULL,
    TOTAL_DAYS DECIMAL(5,1) DEFAULT 0 NOT NULL,
    USED_DAYS DECIMAL(5,1) DEFAULT 0 NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_LEAVE_BALANCE PRIMARY KEY (USER_ID, LEAVE_YEAR)
);

CREATE TABLE IF NOT EXISTS LEAVE_REQUEST (
    LEAVE_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    LEAVE_TYPE VARCHAR(20) NOT NULL,
    START_DE VARCHAR(10) NOT NULL,
    END_DE VARCHAR(10) NOT NULL,
    DAYS DECIMAL(5,1) NOT NULL,
    REASON VARCHAR(500),
    STATUS VARCHAR(20) DEFAULT 'REQUESTED' NOT NULL,
    APPROVER_ID VARCHAR(50),
    APPROVED_DT TIMESTAMP,
    REJECT_REASON VARCHAR(500),
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_LEAVE_REQUEST PRIMARY KEY (LEAVE_ID)
);

CREATE INDEX IF NOT EXISTS IDX_LEAVE_REQUEST_USER ON LEAVE_REQUEST(USER_ID, START_DE);
CREATE INDEX IF NOT EXISTS IDX_LEAVE_REQUEST_STATUS ON LEAVE_REQUEST(STATUS);

-- 기존 사용자에게 올해 기본 15일을 부여한다. 부여 규칙은 대상 프로젝트에서 교체한다.
INSERT INTO LEAVE_BALANCE (USER_ID, LEAVE_YEAR, TOTAL_DAYS, USED_DAYS, REGIST_DT)
SELECT U.USER_ID, CAST(EXTRACT(YEAR FROM CURRENT_DATE) AS VARCHAR(4)), 15, 0, CURRENT_TIMESTAMP
FROM APP_USER U
WHERE NOT EXISTS (
    SELECT 1
    FROM LEAVE_BALANCE B
    WHERE B.USER_ID = U.USER_ID
      AND B.LEAVE_YEAR = CAST(EXTRACT(YEAR FROM CURRENT_DATE) AS VARCHAR(4))
);

