CREATE TABLE IF NOT EXISTS BOARD_VIEW_LOG (
    LOG_ID VARCHAR(40) NOT NULL,
    BOARD_ID VARCHAR(50) NOT NULL,
    BOARD_TYPE VARCHAR(10) NOT NULL,
    VIEW_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_BOARD_VIEW_LOG PRIMARY KEY (LOG_ID)
);

CREATE INDEX IF NOT EXISTS IDX_BOARD_VIEW_LOG_DT ON BOARD_VIEW_LOG(VIEW_DT, BOARD_ID);
CREATE INDEX IF NOT EXISTS IDX_BOARD_VIEW_LOG_BOARD ON BOARD_VIEW_LOG(BOARD_ID, VIEW_DT);

