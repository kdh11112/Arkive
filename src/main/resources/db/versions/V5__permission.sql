-- 메뉴별 권한관리. APP_USER.ADMIN_YN은 슈퍼관리자 통과용으로 유지하고,
-- 일반 사용자의 메뉴 조회/쓰기는 역할(ROLE)로 판단한다.
-- ROLE은 SQL 예약어라 테이블명을 APP_ROLE로 둔다.

CREATE TABLE IF NOT EXISTS APP_ROLE (
    ROLE_ID VARCHAR(30) NOT NULL,
    ROLE_NM VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(500),
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_APP_ROLE PRIMARY KEY (ROLE_ID)
);

CREATE TABLE IF NOT EXISTS APP_USER_ROLE (
    USER_ID VARCHAR(50) NOT NULL,
    ROLE_ID VARCHAR(30) NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APP_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE INDEX IF NOT EXISTS IDX_APP_USER_ROLE_ROLE ON APP_USER_ROLE(ROLE_ID);

-- READ_YN = 메뉴 진입·조회, WRITE_YN = 등록·수정·삭제.
-- WRITE_YN='Y'는 READ_YN='Y'를 전제로 저장한다(서비스에서 보정).
CREATE TABLE IF NOT EXISTS APP_ROLE_MENU (
    ROLE_ID VARCHAR(30) NOT NULL,
    MENU_ID VARCHAR(20) NOT NULL,
    READ_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    WRITE_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_APP_ROLE_MENU PRIMARY KEY (ROLE_ID, MENU_ID)
);

CREATE INDEX IF NOT EXISTS IDX_APP_ROLE_MENU_MENU ON APP_ROLE_MENU(MENU_ID);

