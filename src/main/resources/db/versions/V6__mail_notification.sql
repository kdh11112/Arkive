-- 메일 수신 동의, 중요글 표시, 게시글 알림 1회 발송 여부, 비밀번호 재설정 토큰.
-- 기존 사용자는 수신 동의 없음(MAIL_YN='N')으로 시작한다. 동의는 가입 화면 또는
-- 관리자 사용자 수정 화면에서만 변경한다.
ALTER TABLE APP_USER ADD COLUMN MAIL_YN VARCHAR(1) DEFAULT 'N' NOT NULL;

-- 중요글은 관리자만 지정할 수 있다. 중요글/공지 어느 쪽이든 게시글당 알림은 1회만 보낸다.
ALTER TABLE BOARD ADD COLUMN IMPORTANT_YN VARCHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE BOARD ADD COLUMN MAIL_SENT_YN VARCHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE BOARD ADD COLUMN MAIL_SENT_DT TIMESTAMP;

CREATE INDEX IF NOT EXISTS IDX_BOARD_IMPORTANT ON BOARD(BOARD_TYPE, IMPORTANT_YN);

-- 원문 토큰은 저장하지 않고 SHA-256 해시만 저장한다. 만료/사용 여부는 조회 시 검사한다.
CREATE TABLE IF NOT EXISTS PASSWORD_RESET_TOKEN (
    TOKEN_HASH VARCHAR(64) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    EXPIRES_DT TIMESTAMP NOT NULL,
    USED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_PASSWORD_RESET_TOKEN PRIMARY KEY (TOKEN_HASH)
);

CREATE INDEX IF NOT EXISTS IDX_PASSWORD_RESET_USER ON PASSWORD_RESET_TOKEN(USER_ID);
