-- 3단계: 강의형 콘텐츠. 동영상 1개 + 선택 설문 1세트로 수료를 판정한다.
-- 진도율 기준(기본 90%)과 설문 연계는 샘플 정책이므로 대상 프로젝트에서 교체한다.
CREATE TABLE IF NOT EXISTS LECTURE (
    LECTURE_ID VARCHAR(30) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(2000),
    VIDEO_PATH VARCHAR(500),
    VIDEO_ORIGINAL_NM VARCHAR(255),
    DURATION_SEC INTEGER DEFAULT 0 NOT NULL,
    SURVEY_ID VARCHAR(30),
    COMPLETE_RATE INTEGER DEFAULT 90 NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'DRAFT' NOT NULL,
    USE_YN VARCHAR(1) DEFAULT 'Y' NOT NULL,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_LECTURE PRIMARY KEY (LECTURE_ID)
);

-- 사용자별 최대 재생 위치를 보관한다. 수료는 시청완료 + 설문참여로 계산한다.
CREATE TABLE IF NOT EXISTS LECTURE_PROGRESS (
    LECTURE_ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    WATCHED_SEC INTEGER DEFAULT 0 NOT NULL,
    VIDEO_COMPLETED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    SURVEY_COMPLETED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    COMPLETED_YN VARCHAR(1) DEFAULT 'N' NOT NULL,
    COMPLETED_DT TIMESTAMP,
    REGIST_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDT_DT TIMESTAMP,
    CONSTRAINT PK_LECTURE_PROGRESS PRIMARY KEY (LECTURE_ID, USER_ID),
    CONSTRAINT FK_LECTURE_PROGRESS_LECTURE FOREIGN KEY (LECTURE_ID) REFERENCES LECTURE(LECTURE_ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_LECTURE_STATUS ON LECTURE(STATUS, USE_YN);
CREATE INDEX IF NOT EXISTS IDX_LECTURE_PROGRESS_USER ON LECTURE_PROGRESS(USER_ID, COMPLETED_YN);

