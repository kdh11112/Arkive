-- Arkive 로컬 데모의 최신 HSQLDB 스키마. 빈 DB에만 한 번 실행한다.
-- 변경 이력을 누적하지 않고 각 객체의 최종 정의를 이 파일에서 관리한다.
-- 초기값은 seed.sql, 실행 중 업무 SQL은 Mapper/XML에 둔다.
-- 기존 DB의 갱신용 SQL이나 백업 덤프가 아니다. 다른 DB로 이식할 때는 필요한 객체만
-- 골라 대상 DB 문법에 맞춘다. HSQLDB 서버·초기화 상태 테이블은 이식 대상이 아니다.

